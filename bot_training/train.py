"""Position: board state, layouts, make/unmake, Zobrist hashing. Spec section 7.2."""
EMPTY = '.'
WHITE_PIECES = set('PNBRQK')
BLACK_CHESS_PIECES = set('pnbrqk')
CHECKER_PIECES = set('cC')
ROOK_CASTLE_RIGHT = {0: 'Q', 7: 'K', 56: 'q', 63: 'k'}
KING_START = {'w': 4, 'b': 60}
ROOK_START = {'w': (0, 7), 'b': (56, 63)}

class Side(IntEnum):
    """Which army is to move: the chess army or the checkers army."""
    CHESS = 0
    CHECKERS = 1

class Result(IntEnum):
    """Terminal outcome of a game (spec section 5)."""
    CHESS_WIN = 0
    CHECKERS_WIN = 1
    DRAW = 2

def sq_rf(sq: int) -> tuple[int, int]:
    """0-63 square index -> (rank_idx, file_idx)."""
    return (sq // 8, sq % 8)

def rf_sq(r: int, f: int) -> Optional[int]:
    """(rank_idx, file_idx) -> 0-63 square index, or None if off the board."""
    if 0 <= r < 8 and 0 <= f < 8:
        return r * 8 + f
    return None
_PIECE_CHARS = 'PNBRQKpnbrqkcC'
_rng = random.Random(806485)
ZOBRIST_PIECE = {ch: [_rng.getrandbits(64) for _ in range(64)] for ch in _PIECE_CHARS}
ZOBRIST_SIDE = _rng.getrandbits(64)
ZOBRIST_CASTLING = {ch: _rng.getrandbits(64) for ch in 'KQkq'}
ZOBRIST_EP_FILE = [_rng.getrandbits(64) for _ in range(8)]
ZOBRIST_JUMP_FROM = [_rng.getrandbits(64) for _ in range(64)]

def _layout_standard_24v16() -> list[str]:
    board = [EMPTY] * 64
    back = 'RNBQKBNR'
    for f in range(8):
        board[rf_sq(0, f)] = back[f]
        board[rf_sq(1, f)] = 'P'
    for r in (5, 6, 7):
        for f in range(8):
            board[rf_sq(r, f)] = 'c'
    return board

def _layout_light_16v16() -> list[str]:
    board = [EMPTY] * 64
    back = 'RNBQKBNR'
    for f in range(8):
        board[rf_sq(0, f)] = back[f]
        board[rf_sq(1, f)] = 'P'
    for r in (6, 7):
        for f in range(8):
            board[rf_sq(r, f)] = 'c'
    return board

def _layout_kings_12v16() -> list[str]:
    board = [EMPTY] * 64
    back = 'RNBQKBNR'
    for f in range(8):
        board[rf_sq(0, f)] = back[f]
        board[rf_sq(1, f)] = 'P'
    for r in (6, 7):
        for f in range(8):
            board[rf_sq(r, f)] = 'C'
    return board
LAYOUTS = {'standard_24v16': _layout_standard_24v16, 'light_16v16': _layout_light_16v16, 'kings_12v16': _layout_kings_12v16}

def _layout_chess_only() -> list[str]:
    board = [EMPTY] * 64
    back = 'RNBQKBNR'
    for f in range(8):
        board[rf_sq(0, f)] = back[f]
        board[rf_sq(1, f)] = 'P'
        board[rf_sq(6, f)] = 'p'
        board[rf_sq(7, f)] = back[f].lower()
    return board
STANDARD_FEN = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1'

def parse_fen(fen: str) -> tuple[list[str], str, set, Optional[int], int, int]:
    """Parse a standard chess FEN into engine-internal pieces. Used only by chess_only mode."""
    parts = fen.strip().split()
    board_part, side_part, castle_part, ep_part = (parts[0], parts[1], parts[2], parts[3])
    halfmove = int(parts[4]) if len(parts) > 4 else 0
    fullmove = int(parts[5]) if len(parts) > 5 else 1
    board = [EMPTY] * 64
    ranks = board_part.split('/')
    for i, rank_str in enumerate(ranks):
        r = 7 - i
        f = 0
        for ch in rank_str:
            if ch.isdigit():
                f += int(ch)
            else:
                board[rf_sq(r, f)] = ch
                f += 1
    castling = set((c for c in castle_part if c in 'KQkq'))
    ep_square = None
    if ep_part != '-':
        file_idx = ord(ep_part[0]) - ord('a')
        rank_idx = int(ep_part[1]) - 1
        ep_square = rf_sq(rank_idx, file_idx)
    side = 'w' if side_part == 'w' else 'b'
    return (board, side, castling, ep_square, halfmove, fullmove)

@dataclass
class Undo:
    """Everything Position.make() changed, so unmake() can restore it exactly."""
    mv: int
    moved_piece: str
    frm: int
    to: int
    mtype: MoveType
    captured_piece: str
    captured_square: Optional[int]
    prev_castling: frozenset
    prev_ep_square: Optional[int]
    prev_halfmove_clock: int
    prev_fullmove_number: int
    prev_jump_from: Optional[int]
    prev_side_to_move: Side
    prev_key: int
    rook_frm: Optional[int] = None
    rook_to: Optional[int] = None
    promoted: bool = False

class Position:
    """Board state, side to move, and all rule-relevant state (spec 7.2)."""

    def __init__(self, config: RuleConfig, layout: Optional[str]=None):
        self.config = config
        self.mode = 'hybrid'
        layout_name = layout or config.layout
        if layout_name == 'chess_only_test':
            self.mode = 'chess_only'
            self.board = _layout_chess_only()
            self.chess_color = 'w'
            self.castling = {'K', 'Q', 'k', 'q'}
        else:
            self.board = LAYOUTS[layout_name]()
            self.chess_color = 'w'
            self.castling = {'K', 'Q'}
        self.side_to_move = self._initial_side()
        self.ep_square: Optional[int] = None
        self.halfmove_clock = 0
        self.fullmove_number = 1
        self.jump_from: Optional[int] = None
        self.history: list[int] = []
        self._key = self._compute_key()
        self.history.append(self._key)

    def _initial_side(self) -> Side:
        fm = self.config.first_mover
        if fm == 'chess':
            return Side.CHESS
        if fm == 'checkers':
            return Side.CHECKERS
        return Side.CHESS if random.random() < 0.5 else Side.CHECKERS

    @classmethod
    def from_fen(cls, fen: str, config: RuleConfig) -> 'Position':
        """Standard chess FEN -> chess_only-mode Position (perft/differential test harness only, spec 3.4/9.1)."""
        pos = cls.__new__(cls)
        pos.config = config
        pos.mode = 'chess_only'
        board, side, castling, ep_square, halfmove, fullmove = parse_fen(fen)
        pos.board = board
        pos.chess_color = side
        pos.castling = castling
        pos.side_to_move = Side.CHESS if side == 'w' else Side.CHECKERS
        pos.ep_square = ep_square
        pos.halfmove_clock = halfmove
        pos.fullmove_number = fullmove
        pos.jump_from = None
        pos.history = []
        pos._key = pos._compute_key()
        pos.history.append(pos._key)
        return pos

    def _compute_key(self) -> int:
        k = 0
        for sq, ch in enumerate(self.board):
            if ch != EMPTY:
                k ^= ZOBRIST_PIECE[ch][sq]
        if self.side_to_move == Side.CHECKERS:
            k ^= ZOBRIST_SIDE
        for ch in self.castling:
            k ^= ZOBRIST_CASTLING[ch]
        if self.ep_square is not None:
            k ^= ZOBRIST_EP_FILE[self.ep_square % 8]
        if self.jump_from is not None:
            k ^= ZOBRIST_JUMP_FROM[self.jump_from]
        return k

    def key(self) -> int:
        """Zobrist hash of the full position: board + side + castling + ep + jump_from."""
        return self._key

    def legal_moves(self) -> list[int]:
        """All legal moves for the side to move, as packed ints (spec 7.3)."""
        return legal_moves(self)

    def result(self):
        """Terminal result of the game, or None if it continues (spec 5)."""
        return result(self)

    def copy(self) -> 'Position':
        """Deep-enough copy: board, config reference, and all state fields."""
        pos = Position.__new__(Position)
        pos.config = self.config
        pos.mode = self.mode
        pos.board = list(self.board)
        pos.chess_color = self.chess_color
        pos.castling = set(self.castling)
        pos.side_to_move = self.side_to_move
        pos.ep_square = self.ep_square
        pos.halfmove_clock = self.halfmove_clock
        pos.fullmove_number = self.fullmove_number
        pos.jump_from = self.jump_from
        pos.history = list(self.history)
        pos._key = self._key
        return pos

    def to_planes(self, legal=None):
        """NN input tensor, shape (planes.NUM_PLANES, 8, 8) float32 (spec 7.6).
        `legal` lets a caller that already ran legal_moves() this ply (e.g.
        self_play_game) hand it in instead of making to_planes() recompute
        it for the mobility-map planes; omit it and to_planes() computes its
        own via engine.legal.legal_moves."""
        return to_planes(self, legal=legal)

    def make(self, mv: int) -> Undo:
        """Applies a packed move in place and returns an Undo to reverse it exactly (spec 7.2)."""
        frm, to, mtype = decode(mv)
        moved = self.board[frm]
        captured = EMPTY
        captured_square = None
        undo = Undo(mv=mv, moved_piece=moved, frm=frm, to=to, mtype=mtype, captured_piece=EMPTY, captured_square=None, prev_castling=frozenset(self.castling), prev_ep_square=self.ep_square, prev_halfmove_clock=self.halfmove_clock, prev_fullmove_number=self.fullmove_number, prev_jump_from=self.jump_from, prev_side_to_move=self.side_to_move, prev_key=self._key)
        irreversible = False
        new_ep_square = None
        if mtype == MoveType.CHECKER_STEP:
            self.board[to] = moved
            self.board[frm] = EMPTY
            irreversible = True
            self._maybe_promote_checker(to)
        elif mtype == MoveType.CHECKER_JUMP:
            cap_sq = self._find_captured_between(frm, to)
            captured = self.board[cap_sq]
            captured_square = cap_sq
            self.board[cap_sq] = EMPTY
            self.board[to] = moved
            self.board[frm] = EMPTY
            irreversible = True
            promoted = self._maybe_promote_checker(to)
            undo.promoted = promoted
            if promoted and self.config.promotion_ends_jump_chain:
                self.jump_from = None
                self.side_to_move = Side.CHESS
            else:
                further = self._checker_jumps_from(to)
                if further:
                    self.jump_from = to
                else:
                    self.jump_from = None
                    self.side_to_move = Side.CHESS
        elif mtype in (MoveType.KING_CASTLE, MoveType.QUEEN_CASTLE):
            self.board[to] = moved
            self.board[frm] = EMPTY
            r = frm // 8
            if mtype == MoveType.KING_CASTLE:
                rook_frm, rook_to = (rf_sq(r, 7), rf_sq(r, 5))
            else:
                rook_frm, rook_to = (rf_sq(r, 0), rf_sq(r, 3))
            self.board[rook_to] = self.board[rook_frm]
            self.board[rook_frm] = EMPTY
            undo.rook_frm, undo.rook_to = (rook_frm, rook_to)
            self._clear_castling_rights(moved)
        elif mtype == MoveType.EP_CAPTURE:
            direction = -8 if moved.isupper() else 8
            cap_sq = to + direction
            captured = self.board[cap_sq]
            captured_square = cap_sq
            self.board[cap_sq] = EMPTY
            self.board[to] = moved
            self.board[frm] = EMPTY
            irreversible = True
        elif mtype == MoveType.DOUBLE_PUSH:
            self.board[to] = moved
            self.board[frm] = EMPTY
            new_ep_square = (frm + to) // 2
            irreversible = True
        elif mtype in IS_PROMO:
            if mtype in IS_CAPTURE:
                captured = self.board[to]
                captured_square = to
            promo_char = PROMO_PIECE[mtype]
            self.board[to] = promo_char if moved.isupper() else promo_char.lower()
            self.board[frm] = EMPTY
            irreversible = True
        elif mtype == MoveType.CAPTURE:
            captured = self.board[to]
            captured_square = to
            self.board[to] = moved
            self.board[frm] = EMPTY
            irreversible = True
        else:
            self.board[to] = moved
            self.board[frm] = EMPTY
            if moved.upper() == 'P':
                irreversible = True
        undo.captured_piece = captured
        undo.captured_square = captured_square
        if mtype != MoveType.CHECKER_JUMP:
            if moved.upper() in ('K', 'R') or ROOK_CASTLE_RIGHT.get(frm) or ROOK_CASTLE_RIGHT.get(to):
                self._clear_castling_rights(moved, frm=frm, to=to)
            self.ep_square = new_ep_square
            self.side_to_move = Side.CHECKERS if self.side_to_move == Side.CHESS else Side.CHESS
        if captured != EMPTY:
            irreversible = True
        if irreversible:
            self.halfmove_clock = 0
        else:
            self.halfmove_clock += 1
        if self.side_to_move == Side.CHESS and undo.prev_side_to_move == Side.CHECKERS:
            self.fullmove_number += 1
        self._key = self._compute_key()
        self.history.append(self._key)
        return undo

    def unmake(self, undo: Undo) -> None:
        """Reverses exactly one make() call, restoring the position (spec 7.2)."""
        self.history.pop()
        mtype = undo.mtype
        frm, to = (undo.frm, undo.to)
        if mtype == MoveType.CHECKER_STEP:
            self.board[frm] = undo.moved_piece
            self.board[to] = EMPTY
        elif mtype == MoveType.CHECKER_JUMP:
            self.board[frm] = undo.moved_piece
            self.board[to] = EMPTY
            self.board[undo.captured_square] = undo.captured_piece
        elif mtype in (MoveType.KING_CASTLE, MoveType.QUEEN_CASTLE):
            self.board[frm] = undo.moved_piece
            self.board[to] = EMPTY
            self.board[undo.rook_frm] = self.board[undo.rook_to]
            self.board[undo.rook_to] = EMPTY
        elif mtype == MoveType.EP_CAPTURE:
            self.board[frm] = undo.moved_piece
            self.board[to] = EMPTY
            self.board[undo.captured_square] = undo.captured_piece
        elif mtype in IS_PROMO:
            self.board[frm] = undo.moved_piece
            self.board[to] = undo.captured_piece if mtype in IS_CAPTURE else EMPTY
        elif mtype == MoveType.CAPTURE:
            self.board[frm] = undo.moved_piece
            self.board[to] = undo.captured_piece
        else:
            self.board[frm] = undo.moved_piece
            self.board[to] = EMPTY
        self.castling = set(undo.prev_castling)
        self.ep_square = undo.prev_ep_square
        self.halfmove_clock = undo.prev_halfmove_clock
        self.fullmove_number = undo.prev_fullmove_number
        self.jump_from = undo.prev_jump_from
        self.side_to_move = undo.prev_side_to_move
        self._key = undo.prev_key

    def _clear_castling_rights(self, moved_piece: str, frm: Optional[int]=None, to: Optional[int]=None) -> None:
        if moved_piece == 'K':
            self.castling -= {'K', 'Q'}
        elif moved_piece == 'k':
            self.castling -= {'k', 'q'}
        for sq in (frm, to):
            right = ROOK_CASTLE_RIGHT.get(sq)
            if right:
                self.castling.discard(right)

    def _maybe_promote_checker(self, sq: int) -> bool:
        """Man reaching rank 1 promotes to king. Spec 3.2 promotion rule."""
        if self.board[sq] == 'c' and sq // 8 == 0:
            self.board[sq] = 'C'
            return True
        return False

    def _find_captured_between(self, frm: int, to: int) -> int:
        r0, f0 = sq_rf(frm)
        r1, f1 = sq_rf(to)
        dr = 1 if r1 > r0 else -1
        df = 1 if f1 > f0 else -1
        r, f = (r0 + dr, f0 + df)
        found = None
        while (r, f) != (r1, f1):
            sq = rf_sq(r, f)
            if self.board[sq] != EMPTY:
                found = sq
            r += dr
            f += df
        return found

    def _checker_jumps_from(self, sq: int) -> list[tuple[int, int]]:
        """Pseudo-legal jump destinations for the checker piece at sq (any distance if flying)."""
        piece = self.board[sq]
        if piece not in CHECKER_PIECES:
            return []
        is_king = piece == 'C'
        r0, f0 = sq_rf(sq)
        results = []
        directions = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
        if not is_king:
            directions = [(-1, 1), (-1, -1)]
        for dr, df in directions:
            if is_king and self.config.flying_kings:
                r, f = (r0 + dr, f0 + df)
                path_clear = []
                while True:
                    mid = rf_sq(r, f)
                    if mid is None:
                        break
                    if self.board[mid] == EMPTY:
                        path_clear.append(mid)
                        r += dr
                        f += df
                        continue
                    target_piece = self.board[mid]
                    king_exempt = target_piece == 'K' and self.config.king_capture_immunity
                    if target_piece not in CHECKER_PIECES and (not king_exempt):
                        lr, lf = (r + dr, f + df)
                        while True:
                            land = rf_sq(lr, lf)
                            if land is None or self.board[land] != EMPTY:
                                break
                            results.append((mid, land))
                            lr += dr
                            lf += df
                    break
            else:
                mid = rf_sq(r0 + dr, f0 + df)
                if mid is None:
                    continue
                mid_piece = self.board[mid]
                king_exempt = mid_piece == 'K' and self.config.king_capture_immunity
                if mid_piece == EMPTY or king_exempt or mid_piece in CHECKER_PIECES:
                    continue
                land = rf_sq(r0 + 2 * dr, f0 + 2 * df)
                if land is not None and self.board[land] == EMPTY:
                    results.append((mid, land))
        return results

    def repetition_count(self) -> int:
        """How many times the current position's key has occurred in this game's history."""
        return self.history.count(self._key)

    def to_fen(self) -> str:
        """Standard chess FEN export. Only meaningful in chess_only mode."""
        rows = []
        for r in range(7, -1, -1):
            row = ''
            empties = 0
            for f in range(8):
                ch = self.board[rf_sq(r, f)]
                if ch == EMPTY:
                    empties += 1
                else:
                    if empties:
                        row += str(empties)
                        empties = 0
                    row += ch
            if empties:
                row += str(empties)
            rows.append(row)
        board_part = '/'.join(rows)
        side_part = 'w' if self.side_to_move == Side.CHESS else 'b'
        castle_part = ''.join((c for c in 'KQkq' if c in self.castling)) or '-'
        ep_part = '-'
        if self.ep_square is not None:
            r, f = sq_rf(self.ep_square)
            ep_part = f"{chr(ord('a') + f)}{r + 1}"
        return f'{board_part} {side_part} {castle_part} {ep_part} {self.halfmove_clock} {self.fullmove_number}'


# ==== engine/attacks.py ====
"""Attack detection. Spec section 3.5 (is_attacked_by_checkers) plus a generic
standard-chess attack function used only by the chess-only perft/differential mode.
"""
DIAG4 = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
KNIGHT_OFFS = [(1, 2), (2, 1), (2, -1), (1, -2), (-1, -2), (-2, -1), (-2, 1), (-1, 2)]
ORTHO4 = [(1, 0), (-1, 0), (0, 1), (0, -1)]

def checkers_attacking(position: Position, square: int) -> list[int]:
    """Spec 3.5: source square(s) of every checker that can jump X (`square`)
    and land empty. Direction d = (dr, df) is the direction of travel
    S -> X -> L. Men only travel with dr == -1 (toward rank 1, spec 3.2).
    Kings travel any of the four diagonals; flying kings (config) may source
    the jump from any distance along the diagonal provided the path is clear
    (spec 3.2). Empty list == not attacked; is_attacked_by_checkers is just
    bool(this)."""
    board = position.board
    flying = position.config.flying_kings
    r1, f1 = sq_rf(square)
    sources = []
    for dr, df in DIAG4:
        land = rf_sq(r1 + dr, f1 + df)
        if land is None or board[land] != EMPTY:
            continue
        r, f = (r1 - dr, f1 - df)
        first = True
        while True:
            s = rf_sq(r, f)
            if s is None:
                break
            piece = board[s]
            if piece == EMPTY:
                if not flying:
                    break
                r -= dr
                f -= df
                first = False
                continue
            if piece == 'c' and first and (dr == -1):
                sources.append(s)
            elif piece == 'C' and (first or flying):
                sources.append(s)
            break
    return sources

def is_attacked_by_checkers(position: Position, square: int) -> bool:
    """Spec 3.5: X is attacked if a checker on S can jump it and land empty."""
    return bool(checkers_attacking(position, square))

def _find_king(board: list[str], king_char: str) -> int | None:
    for sq, ch in enumerate(board):
        if ch == king_char:
            return sq
    return None

def is_square_attacked_by_chess(position: Position, square: int, by_white: bool) -> bool:
    """Standard FIDE attack detection, used only in chess_only mode (perft/differential)."""
    board = position.board
    r1, f1 = sq_rf(square)
    pawn, knight, bishop, rook, queen, king = 'PNBRQK' if by_white else 'pnbrqk'
    pawn_dr = -1 if by_white else 1
    for df in (1, -1):
        s = rf_sq(r1 + pawn_dr, f1 + df)
        if s is not None and board[s] == pawn:
            return True
    for dr, df in KNIGHT_OFFS:
        s = rf_sq(r1 + dr, f1 + df)
        if s is not None and board[s] == knight:
            return True
    for dr, df in DIAG4:
        s = rf_sq(r1 + dr, f1 + df)
        if s is not None and board[s] == king:
            return True
    for dr, df in ORTHO4:
        s = rf_sq(r1 + dr, f1 + df)
        if s is not None and board[s] == king:
            return True
    for dr, df in DIAG4:
        r, f = (r1 + dr, f1 + df)
        while True:
            s = rf_sq(r, f)
            if s is None:
                break
            piece = board[s]
            if piece == EMPTY:
                r += dr
                f += df
                continue
            if piece == bishop or piece == queen:
                return True
            break
    for dr, df in ORTHO4:
        r, f = (r1 + dr, f1 + df)
        while True:
            s = rf_sq(r, f)
            if s is None:
                break
            piece = board[s]
            if piece == EMPTY:
                r += dr
                f += df
                continue
            if piece == rook or piece == queen:
                return True
            break
    return False


# ==== engine/chess_gen.py ====
"""Pseudo-legal chess move generation. Spec section 3.1.

Generic over colour so it can serve both the real game (white/CHESS side only)
and the chess-only perft/differential test mode (both colours).
"""
KNIGHT_OFFS = [(1, 2), (2, 1), (2, -1), (1, -2), (-1, -2), (-2, -1), (-2, 1), (-1, 2)]
DIAG4 = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
ORTHO4 = [(1, 0), (-1, 0), (0, 1), (0, -1)]
KING8 = DIAG4 + ORTHO4

def _own_enemy_sets(color: str, chess_only: bool) -> tuple[set, set]:
    if color == 'w':
        own = WHITE_PIECES
        enemy = (BLACK_CHESS_PIECES if chess_only else set()) | CHECKER_PIECES
    else:
        own = BLACK_CHESS_PIECES
        enemy = WHITE_PIECES | (CHECKER_PIECES if not chess_only else set())
    return (own, enemy)

def pseudo_legal_chess_moves(position: Position, color: str) -> list[int]:
    """All pseudo-legal moves for the chess pieces of `color` ('w' or 'b')."""
    board = position.board
    chess_only = position.mode == 'chess_only'
    own, enemy = _own_enemy_sets(color, chess_only)
    moves: list[int] = []
    forward = 1 if color == 'w' else -1
    start_rank = 1 if color == 'w' else 6
    promo_rank = 7 if color == 'w' else 0
    pawn_char = 'P' if color == 'w' else 'p'
    knight_char = 'N' if color == 'w' else 'n'
    bishop_char = 'B' if color == 'w' else 'b'
    rook_char = 'R' if color == 'w' else 'r'
    queen_char = 'Q' if color == 'w' else 'q'
    king_char = 'K' if color == 'w' else 'k'
    for sq in range(64):
        piece = board[sq]
        if piece == EMPTY or piece not in own:
            continue
        r, f = sq_rf(sq)
        if piece == pawn_char:
            one = rf_sq(r + forward, f)
            if one is not None and board[one] == EMPTY:
                if r + forward == promo_rank:
                    for mt in (MoveType.PROMO_N, MoveType.PROMO_B, MoveType.PROMO_R, MoveType.PROMO_Q):
                        moves.append(encode(sq, one, mt))
                else:
                    moves.append(encode(sq, one, MoveType.QUIET))
                    if r == start_rank:
                        two = rf_sq(r + 2 * forward, f)
                        if two is not None and board[two] == EMPTY:
                            moves.append(encode(sq, two, MoveType.DOUBLE_PUSH))
            for df in (-1, 1):
                cap = rf_sq(r + forward, f + df)
                if cap is None:
                    continue
                if board[cap] in enemy:
                    if r + forward == promo_rank:
                        for mt in (MoveType.PROMO_CAP_N, MoveType.PROMO_CAP_B, MoveType.PROMO_CAP_R, MoveType.PROMO_CAP_Q):
                            moves.append(encode(sq, cap, mt))
                    else:
                        moves.append(encode(sq, cap, MoveType.CAPTURE))
                elif position.ep_square is not None and cap == position.ep_square:
                    moves.append(encode(sq, cap, MoveType.EP_CAPTURE))
        elif piece == knight_char:
            for dr, df in KNIGHT_OFFS:
                to = rf_sq(r + dr, f + df)
                if to is None or board[to] in own:
                    continue
                mt = MoveType.CAPTURE if board[to] in enemy else MoveType.QUIET
                moves.append(encode(sq, to, mt))
        elif piece == king_char:
            for dr, df in KING8:
                to = rf_sq(r + dr, f + df)
                if to is None or board[to] in own:
                    continue
                mt = MoveType.CAPTURE if board[to] in enemy else MoveType.QUIET
                moves.append(encode(sq, to, mt))
            moves.extend(_castle_moves(position, color))
        elif piece in (bishop_char, rook_char, queen_char):
            dirs = DIAG4 if piece == bishop_char else ORTHO4 if piece == rook_char else KING8
            for dr, df in dirs:
                rr, ff = (r + dr, f + df)
                while True:
                    to = rf_sq(rr, ff)
                    if to is None or board[to] in own:
                        break
                    if board[to] in enemy:
                        moves.append(encode(sq, to, MoveType.CAPTURE))
                        break
                    moves.append(encode(sq, to, MoveType.QUIET))
                    rr += dr
                    ff += df
    return moves

def _castle_moves(position: Position, color: str) -> list[int]:
    """Structural pseudo-legality only (rights, empty path, rook present).
    Check-safety conditions (spec 3.3 items 3-5) are applied in legal.py."""
    board = position.board
    moves = []
    if color == 'w':
        king_sq, rank = (4, 0)
        k_right, q_right = ('K', 'Q')
        rook_k, rook_q = (7, 0)
        king_char, rook_char = ('K', 'R')
    else:
        king_sq, rank = (60, 7)
        k_right, q_right = ('k', 'q')
        rook_k, rook_q = (63, 56)
        king_char, rook_char = ('k', 'r')
    if board[king_sq] != king_char:
        return moves
    if k_right in position.castling and board[rook_k] == rook_char:
        f1, f2 = (rf_sq(rank, 5), rf_sq(rank, 6))
        if board[f1] == EMPTY and board[f2] == EMPTY:
            moves.append(encode(king_sq, rf_sq(rank, 6), MoveType.KING_CASTLE))
    if q_right in position.castling and board[rook_q] == rook_char:
        f1, f2, f3 = (rf_sq(rank, 1), rf_sq(rank, 2), rf_sq(rank, 3))
        if board[f1] == EMPTY and board[f2] == EMPTY and (board[f3] == EMPTY):
            moves.append(encode(king_sq, rf_sq(rank, 2), MoveType.QUEEN_CASTLE))
    return moves


# ==== engine/checkers_gen.py ====
"""Pseudo-legal checkers move generation: steps, jumps, chains. Spec section 3.2."""
DIAG4 = [(1, 1), (1, -1), (-1, 1), (-1, -1)]
MAN_FORWARD = [(-1, 1), (-1, -1)]

def _checker_steps_from(position: Position, sq: int) -> list[int]:
    piece = position.board[sq]
    is_king = piece == 'C'
    dirs = DIAG4 if is_king else MAN_FORWARD
    r0, f0 = sq_rf(sq)
    results = []
    if is_king and position.config.flying_kings:
        for dr, df in dirs:
            r, f = (r0 + dr, f0 + df)
            while True:
                to = rf_sq(r, f)
                if to is None or position.board[to] != EMPTY:
                    break
                results.append(to)
                r += dr
                f += df
    else:
        for dr, df in dirs:
            to = rf_sq(r0 + dr, f0 + df)
            if to is not None and position.board[to] == EMPTY:
                results.append(to)
    return results

def pseudo_legal_checker_moves(position: Position) -> tuple[list[int], list[int]]:
    """Returns (steps, jumps) as packed moves, ignoring mandatory/maximal capture rules."""
    steps: list[int] = []
    jumps: list[int] = []
    board = position.board
    for sq in range(64):
        if board[sq] not in ('c', 'C'):
            continue
        for to in _checker_steps_from(position, sq):
            steps.append(encode(sq, to, MoveType.CHECKER_STEP))
        for _mid, land in position._checker_jumps_from(sq):
            jumps.append(encode(sq, land, MoveType.CHECKER_JUMP))
    return (steps, jumps)

def _chain_length(position: Position, mv: int) -> int:
    """Total captures achievable by playing mv and then continuing optimally (recursive lookahead)."""
    _frm, to, _mt = decode(mv)
    undo = position.make(mv)
    if position.jump_from == to:
        further = [encode(to, land, MoveType.CHECKER_JUMP) for _m, land in position._checker_jumps_from(to)]
        best = max((_chain_length(position, j) for j in further), default=0)
        total = 1 + best
    else:
        total = 1
    position.unmake(undo)
    return total

def legal_checker_moves(position: Position) -> list[int]:
    """Applies jump-continuation lock, mandatory capture, and maximal capture (spec 3.2)."""
    if position.jump_from is not None:
        sq = position.jump_from
        return [encode(sq, land, MoveType.CHECKER_JUMP) for _m, land in position._checker_jumps_from(sq)]
    steps, jumps = pseudo_legal_checker_moves(position)
    if not jumps:
        return steps
    if not position.config.mandatory_capture:
        return steps + jumps
    if position.config.maximal_capture:
        lengths = [_chain_length(position, mv) for mv in jumps]
        best = max(lengths)
        return [mv for mv, length in zip(jumps, lengths) if length == best]
    return jumps


# ==== engine/legal.py ====
"""Legality filter. Spec section 3.5 and the Correctness Traps of 3.6.

The chess side's legality is determined purely by make-the-move / check-attack /
unmake-the-move. No pins, no discovered-check special casing: they all fall out
of evaluating attacks strictly *after* the candidate move (Trap 1, Trap 2).
"""

def _find_king(board: list[str], king_char: str):
    for sq, ch in enumerate(board):
        if ch == king_char:
            return sq
    return None

def _square_attacked(position: Position, sq: int, own_color: str) -> bool:
    if position.mode == 'chess_only':
        return is_square_attacked_by_chess(position, sq, by_white=own_color == 'b')
    return is_attacked_by_checkers(position, sq)

def _castle_pre_checks(position: Position, color: str, mtype: MoveType) -> bool:
    """Spec 3.3 conditions 3 & 4: not currently in check, doesn't pass through an
    attacked square. Condition 5 (landing square attacked) falls out of the
    generic post-make filter applied to every pseudo-legal move."""
    king_sq = 4 if color == 'w' else 60
    if _square_attacked(position, king_sq, color):
        return False
    rank = king_sq // 8
    pass_file = 5 if mtype == MoveType.KING_CASTLE else 3
    pass_sq = rf_sq(rank, pass_file)
    king_char = position.board[king_sq]
    position.board[king_sq] = EMPTY
    position.board[pass_sq] = king_char
    attacked = _square_attacked(position, pass_sq, color)
    position.board[pass_sq] = EMPTY
    position.board[king_sq] = king_char
    return not attacked

def legal_moves(position: Position) -> list[int]:
    """All legal moves for the side to move (spec 3.5): checkers dispatch to
    checkers_gen; chess moves are pseudo-legal-generated then filtered by
    make/attack/unmake, which handles pins, discovered checks, and Traps 1-4
    (spec 3.6) without any special-casing."""
    if position.side_to_move == Side.CHECKERS and position.mode == 'hybrid':
        return legal_checker_moves(position)
    color = 'w' if position.side_to_move == Side.CHESS else 'b'
    king_char = 'K' if color == 'w' else 'k'
    pseudo = pseudo_legal_chess_moves(position, color)
    if position.mode == 'hybrid' and (not position.config.king_capture_immunity):
        return pseudo
    legal = []
    for mv in pseudo:
        _frm, _to, mtype = decode(mv)
        if mtype in (MoveType.KING_CASTLE, MoveType.QUEEN_CASTLE):
            if not _castle_pre_checks(position, color, mtype):
                continue
        undo = position.make(mv)
        king_sq = _find_king(position.board, king_char)
        safe = king_sq is None or not _square_attacked(position, king_sq, color)
        position.unmake(undo)
        if safe:
            legal.append(mv)
    return legal

def in_check(position: Position) -> bool:
    """Is the chess king (of the side to move, chess-only mode aware) currently attacked?"""
    color = 'w' if position.side_to_move == Side.CHESS else 'b'
    if position.mode == 'hybrid' and position.side_to_move != Side.CHESS:
        return False
    king_char = 'K' if color == 'w' else 'k'
    king_sq = _find_king(position.board, king_char)
    if king_sq is None:
        return False
    return _square_attacked(position, king_sq, color)


# ==== engine/terminal.py ====
"""Win/draw detection. Spec section 5. Order of evaluation matters (5, table)."""

def result(position: Position) -> Result | None:
    """None if the game continues. Evaluated in the order given in spec section 5."""
    if position.mode != 'hybrid':
        return _chess_only_result(position)
    if not position.config.king_capture_immunity and 'K' not in position.board:
        return Result.CHECKERS_WIN
    checkers_left = sum((1 for ch in position.board if ch in ('c', 'C')))
    if checkers_left == 0:
        return Result.CHESS_WIN
    if position.side_to_move == Side.CHECKERS:
        if not legal_moves(position):
            return Result.CHESS_WIN
    elif not legal_moves(position):
        return Result.CHECKERS_WIN
    if position.repetition_count() >= 3:
        return Result.DRAW
    if position.halfmove_clock >= position.config.fifty_move_plies:
        return Result.DRAW
    return None

def _chess_only_result(position: Position) -> Result | None:
    """Plain chess terminal detection, used only by the perft/differential test mode."""
    if not legal_moves(position):
        if in_check(position):
            return Result.CHECKERS_WIN if position.side_to_move == Side.CHESS else Result.CHESS_WIN
        return Result.DRAW
    if position.repetition_count() >= 3:
        return Result.DRAW
    if position.halfmove_clock >= position.config.fifty_move_plies:
        return Result.DRAW
    return None


# ==== engine/serialize.py ====
"""State string read/write and human-readable move notation. Spec section 7.5."""

def serialize(position: Position) -> str:
    """Position -> the FEN-like state string of spec 7.5. Round-trips exactly with deserialize()."""
    rows = []
    for r in range(7, -1, -1):
        row = ''
        empty_count = 0
        for f in range(8):
            ch = position.board[r * 8 + f]
            if ch == EMPTY:
                empty_count += 1
            else:
                if empty_count:
                    row += str(empty_count)
                    empty_count = 0
                row += ch
        if empty_count:
            row += str(empty_count)
        rows.append(row)
    board_str = '|'.join(rows)
    side = 'w' if position.side_to_move == Side.CHESS else 'b'
    castling = ''.join((c for c in 'KQ' if c in position.castling)) or '-'
    ep = square_name(position.ep_square) if position.ep_square is not None else '-'
    jf = square_name(position.jump_from) if position.jump_from is not None else '-'
    return '/'.join([board_str, side, castling, ep, str(position.halfmove_clock), str(position.fullmove_number), jf, position.config.config_hash()])

def deserialize(state: str, config: RuleConfig) -> Position:
    """State string -> Position. Raises ValueError on malformed input or a
    config-hash mismatch (spec 7.5: never silently proceed on a mismatch)."""
    parts = state.split('/')
    if len(parts) != 8:
        raise ValueError(f'malformed state string: expected 8 fields, got {len(parts)}')
    board_str, side, castling, ep, halfmove, fullmove, jf, cfg_hash = parts
    if cfg_hash != config.config_hash():
        raise ValueError('state was serialized under a different RuleConfig')
    board = [EMPTY] * 64
    rows = board_str.split('|')
    if len(rows) != 8:
        raise ValueError('malformed state string: expected 8 ranks')
    for i, row in enumerate(rows):
        r = 7 - i
        f = 0
        for ch in row:
            if ch.isdigit():
                f += int(ch)
            else:
                if f > 7:
                    raise ValueError('malformed state string: rank overflow')
                board[rf_sq(r, f)] = ch
                f += 1
    pos = Position.__new__(Position)
    pos.config = config
    pos.mode = 'hybrid'
    pos.board = board
    pos.chess_color = 'w'
    pos.castling = set((c for c in castling if c in 'KQ'))
    pos.side_to_move = Side.CHESS if side == 'w' else Side.CHECKERS
    pos.ep_square = square_from_name(ep) if ep != '-' else None
    pos.halfmove_clock = int(halfmove)
    pos.fullmove_number = int(fullmove)
    pos.jump_from = square_from_name(jf) if jf != '-' else None
    pos.history = []
    pos._key = pos._compute_key()
    pos.history.append(pos._key)
    return pos

def move_to_str(position: Position, mv: int) -> str:
    """SAN-ish notation: piece letter (chess only) + from + capture marker + to + promotion."""
    frm, to, mtype = decode(mv)
    piece = position.board[frm]
    is_capture = position.board[to] != EMPTY or mtype in (MoveType.EP_CAPTURE, MoveType.CHECKER_JUMP)
    if mtype == MoveType.KING_CASTLE:
        return 'O-O'
    if mtype == MoveType.QUEEN_CASTLE:
        return 'O-O-O'
    prefix = piece.upper() if piece.upper() not in ('P', 'C') else ''
    sep = 'x' if is_capture else '-'
    s = f'{prefix}{square_name(frm)}{sep}{square_name(to)}'
    if mtype in PROMO_PIECE:
        s += f'={PROMO_PIECE[mtype]}'
    return s


# ==== engine/planes.py ====
"""to_planes(): NN input tensor. Spec section 7.6. Unused by anything today;
built now so the future training phase has a stable interface to target."""
CHESS_PIECE_ORDER = 'PNBRQK'
MOBILITY_PIECE_ORDER = 'PNBRQKcC'
NUM_PLANES = 21 + len(MOBILITY_PIECE_ORDER)

def to_planes(position: Position, legal=None) -> np.ndarray:
    """Position -> (NUM_PLANES, 8, 8) float32 NN input tensor (spec 7.6).
    `legal` is the side-to-move's legal_moves() list, if the caller already
    has one (e.g. mid self-play) — pass it in to skip recomputing it here
    for the mobility planes. Left None, to_planes computes its own."""
    planes = np.zeros((NUM_PLANES, 8, 8), dtype=np.float32)
    idx = 0
    for piece_char in CHESS_PIECE_ORDER:
        for sq, ch in enumerate(position.board):
            if ch == piece_char:
                r, f = sq_rf(sq)
                planes[idx, r, f] = 1.0
        idx += 1
    for piece_char in ('c', 'C'):
        for sq, ch in enumerate(position.board):
            if ch == piece_char:
                r, f = sq_rf(sq)
                planes[idx, r, f] = 1.0
        idx += 1
    for r in range(8):
        for f in range(8):
            planes[idx, r, f] = 1.0 if (r + f) % 2 == 1 else 0.0
    idx += 1
    for right in ('K', 'Q', 'k', 'q'):
        planes[idx, :, :] = 1.0 if right in position.castling else 0.0
        idx += 1
    if position.ep_square is not None:
        r, f = sq_rf(position.ep_square)
        planes[idx, r, f] = 1.0
    idx += 1
    planes[idx, :, :] = 1.0 if position.side_to_move == Side.CHECKERS else 0.0
    idx += 1
    if position.jump_from is not None:
        r, f = sq_rf(position.jump_from)
        planes[idx, r, f] = 1.0
    idx += 1
    planes[idx, :, :] = min(position.halfmove_clock / position.config.fifty_move_plies, 1.0)
    idx += 1
    rep = position.repetition_count()
    planes[idx, :, :] = 1.0 if rep >= 2 else 0.0
    idx += 1
    planes[idx, :, :] = 1.0 if rep >= 3 else 0.0
    idx += 1
    king_sq = None
    for sq, ch in enumerate(position.board):
        if ch == 'K':
            king_sq = sq
            break
    threats = checkers_attacking(position, king_sq) if king_sq is not None else []
    planes[idx, :, :] = 1.0 if threats else 0.0
    idx += 1
    for s in threats:
        r, f = sq_rf(s)
        planes[idx, r, f] = 1.0
    idx += 1
    if legal is None:
        legal = _legal_moves(position)
    mobility_idx = {ch: idx + i for i, ch in enumerate(MOBILITY_PIECE_ORDER)}
    for mv in legal:
        frm, to, _mtype = decode(mv)
        plane = mobility_idx.get(position.board[frm])
        if plane is not None:
            r, f = sq_rf(to)
            planes[plane, r, f] = 1.0
    idx += len(MOBILITY_PIECE_ORDER)
    assert idx == NUM_PLANES
    return planes


